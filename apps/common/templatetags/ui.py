@register.filter
def language_color(name):
    return LANGUAGE_COLORS.get(name, "#8b949e")
@register.filter
def top_language(languages):
    return next(iter(languages or {}), "")
@register.filter
def initials(user):
    """Two-letter avatar text from the person's name, falling back to their public handle."""
    letters = (getattr(user, "first_name", "")[:1] + getattr(user, "last_name", "")[:1]).upper()
    if letters:
        return letters
    profile = getattr(user, "profile", None)
    return (getattr(profile, "handle", "") or "?")[:2].upper()
@register.filter
def tone(obj):
    """Stable muted background tone (tone-0..tone-5) for items without an image."""
    return f"tone-{(getattr(obj, 'pk', 0) or 0) % 6}"
@register.filter
def avatar_tone(user):
    """Stable pastel color class (av-0..av-7) for a person's initials."""
    return f"av-{(getattr(user, 'pk', 0) or 0) % 8}"
