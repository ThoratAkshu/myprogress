@register.simple_tag
def icon(name, size=20, label=""):
    """Inline SVG icon. Decorative unless a label is given."""
    accessibility = format_html('role="img" aria-label="{}"', label) if label else mark_safe('aria-hidden="true"')
    return format_html('<svg class="icon icon-{}" width="{}" height="{}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" focusable="false" {}>{}</svg>', name, size, size, accessibility, mark_safe(ICONS[name]))
