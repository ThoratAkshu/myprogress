        starts = (timezone.localtime() + timedelta(hours=3)).strftime("%Y-%m-%dT%H:%M")
        response = self.client.post(reverse("organizations:classes", args=[self.organization.slug]), {"title": "Live: REST APIs", "starts_at": starts, "duration_minutes": "60", "meeting_link": "", "group": "Batch A", "agenda": ""})
        live = LiveClass.objects.get()
        self.assertRedirects(response, reverse("organizations:live_class", args=[self.organization.slug, live.pk]))
        self.assertEqual(live.meeting_link, "")  # no link: the class happens inside MyProgress, no outside account needed
        self.assertTrue(live.in_myprogress)
        self.assertTrue(Notification.objects.filter(recipient=self.student, text__startswith="Live class scheduled: Live: REST APIs").exists())
        self.assertFalse(Notification.objects.filter(recipient=other, text__startswith="Live class scheduled").exists())
