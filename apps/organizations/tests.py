    def test_live_classes_take_attendance_and_feed_growth(self):
        from io import StringIO
        from django.core.management import call_command
        from .models import Attendance, LiveClass
        self.join(self.student, group="Batch A")
        late_student = make_user("late@example.com", "Lay", "Te")
        self.join(late_student, group="Batch A")
        other = make_user("other@example.com", "Oth", "Er")
        self.join(other, group="Batch B")
